"""
01 - Python Function Basics

A function is a reusable block of code that performs a specific task.

Key concepts:
- Define a function with the `def` keyword.
- Indent the code inside the function.
- Call the function by writing its name followed by parentheses.
- The function body runs when the function is called.
- Use descriptive function names in snake_case.
"""


# 1. Define a function
def greet():
    """Print a greeting."""
    print("Hello! Welcome to Python functions.")


# 2. Call the function
greet()


# 3. A function runs each time it is called
greet()
