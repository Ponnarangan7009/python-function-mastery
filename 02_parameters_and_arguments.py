"""
02 - Parameters and Arguments

A parameter is a variable listed in a function definition.
An argument is a value passed to the function when it is called.

This example shows how a function can use a parameter to work
with different values.
"""


# Define a function with one parameter called name
def greet(name):
    """Print a personalized greeting."""
    print(f"Hello, {name}!")


# Call the function with arguments
greet("Asha")
greet("Ravi")
